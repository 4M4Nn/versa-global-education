// Auto-detects the sequential hero frame images in public/hero-frames and
// writes a typed manifest. Re-run automatically via the "prebuild" script
// whenever the frame set changes -- filenames are never hand-typed.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const FRAMES_DIR = join(__dirname, "..", "public", "hero-frames")
const OUT_FILE = join(__dirname, "..", "src", "lib", "heroFrames.ts")

const IMAGE_EXT = /\.(jpe?g|png|webp)$/i

function naturalCompare(a, b) {
  const numsA = a.match(/\d+/g)?.map(Number) ?? []
  const numsB = b.match(/\d+/g)?.map(Number) ?? []
  const len = Math.max(numsA.length, numsB.length)
  for (let i = 0; i < len; i++) {
    const diff = (numsA[i] ?? 0) - (numsB[i] ?? 0)
    if (diff !== 0) return diff
  }
  return a.localeCompare(b)
}

const files = readdirSync(FRAMES_DIR)
  .filter((f) => IMAGE_EXT.test(f))
  .sort(naturalCompare)

if (files.length === 0) {
  throw new Error(`No frame images found in ${FRAMES_DIR}`)
}

const banner = "// AUTO-GENERATED by scripts/generate-hero-frames.mjs -- do not edit by hand."
const body = `${banner}
export const HERO_FRAMES: readonly string[] = [
${files.map((f) => `  "/hero-frames/${f}",`).join("\n")}
] as const

export const HERO_FRAME_COUNT = HERO_FRAMES.length
`

mkdirSync(dirname(OUT_FILE), { recursive: true })
writeFileSync(OUT_FILE, body)

console.log(`Generated ${OUT_FILE} with ${files.length} frames.`)
